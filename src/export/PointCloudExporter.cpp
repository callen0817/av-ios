uint32_t PointCloudExporter::computeE57Crc32c(const uint8_t* data, size_t len) {
    // ASTM E2807-11 Section 8.2.1: Castagnoli CRC-32C (reflected polynomial 0x82F63B78)
    uint32_t crc = 0xFFFFFFFFu;
    for (size_t i = 0; i < len; ++i) {
        crc ^= static_cast<uint32_t>(data[i]);
        for (int b = 0; b < 8; ++b) {
            uint32_t mask = -(crc & 1u);
            crc = (crc >> 1) ^ (0x82F63B78u & mask);
        }
    }
    return ~crc;
}

bool PointCloudExporter::exportToPly(const std::string& file_path,
                                     const std::vector<core::LidarPointXYZIRT>& points,
                                     bool binary_format) {
    std::ofstream out(file_path, binary_format ? (std::ios::binary | std::ios::trunc) : std::ios::trunc);
    if (!out.is_open()) return false;

    out << "ply\n";
    out << (binary_format ? "format binary_little_endian 1.0\n" : "format ascii 1.0\n");
    out << "comment Generated by AV Scan iOS Commercial SLAM Engine\n";
    out << "element vertex " << points.size() << "\n";
    out << "property float x\n";
    out << "property float y\n";
    out << "property float z\n";
    out << "property float intensity\n";
    out << "property uchar red\n";
    out << "property uchar green\n";
    out << "property uchar blue\n";
    out << "end_header\n";

    if (binary_format) {
        #pragma pack(push, 1)
        struct PlyVertex {
            float x, y, z, intensity;
            uint8_t r, g, b;
        };
        #pragma pack(pop)
        for (const auto& pt : points) {
            PlyVertex v{
                static_cast<float>(pt.x),
                static_cast<float>(pt.y),
                static_cast<float>(pt.z),
                pt.intensity,
                pt.r, pt.g, pt.b
            };
            out.write(reinterpret_cast<const char*>(&v), sizeof(PlyVertex));
        }
    } else {
        out << std::fixed << std::setprecision(5);
        for (const auto& pt : points) {
            out << pt.x << " " << pt.y << " " << pt.z << " "
                << pt.intensity << " "
                << static_cast<int>(pt.r) << " "
                << static_cast<int>(pt.g) << " "
                << static_cast<int>(pt.b) << "\n";
        }
    }
    return out.good();
}

bool PointCloudExporter::readFromPly(const std::string& file_path,
                                     std::vector<core::LidarPointXYZIRT>& out_points) {
    out_points.clear();
    std::ifstream in(file_path, std::ios::binary);
    if (!in.is_open()) return false;

    std::string line;
    bool is_binary = false;
    size_t vertex_count = 0;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.find("format binary_little_endian") != std::string::npos) is_binary = true;
        if (line.rfind("element vertex ", 0) == 0) {
            vertex_count = std::stoull(line.substr(15));
        }
        if (line == "end_header") break;
    }

    out_points.reserve(vertex_count);
    if (is_binary) {
        #pragma pack(push, 1)
        struct PlyVertex {
            float x, y, z, intensity;
            uint8_t r, g, b;
        };
        #pragma pack(pop)
        for (size_t i = 0; i < vertex_count; ++i) {
            PlyVertex v{};
            in.read(reinterpret_cast<char*>(&v), sizeof(PlyVertex));
            if (!in.good()) return false;
            core::LidarPointXYZIRT pt;
            pt.x = v.x; pt.y = v.y; pt.z = v.z;
            pt.intensity = v.intensity;
            pt.r = v.r; pt.g = v.g; pt.b = v.b;
            pt.colorized = true;
            out_points.push_back(pt);
        }
    } else {
        for (size_t i = 0; i < vertex_count; ++i) {
            core::LidarPointXYZIRT pt;
            int r = 0, g = 0, b = 0;
            if (!(in >> pt.x >> pt.y >> pt.z >> pt.intensity >> r >> g >> b)) return false;
            pt.r = static_cast<uint8_t>(r);
            pt.g = static_cast<uint8_t>(g);
            pt.b = static_cast<uint8_t>(b);
            pt.colorized = true;
            out_points.push_back(pt);
        }
    }
    return out_points.size() == vertex_count;
}

bool PointCloudExporter::exportToPcd(const std::string& file_path,
                                     const std::vector<core::LidarPointXYZIRT>& points,
                                     bool binary_format) {
    std::ofstream out(file_path, binary_format ? (std::ios::binary | std::ios::trunc) : std::ios::trunc);
    if (!out.is_open()) return false;

    out << "# .PCD v0.7 - Point Cloud Data file format\n";
    out << "VERSION 0.7\n";
    out << "FIELDS x y z intensity rgb\n";
    out << "SIZE 4 4 4 4 4\n";
    out << "TYPE F F F F U\n";
    out << "COUNT 1 1 1 1 1\n";
    out << "WIDTH " << points.size() << "\n";
    out << "HEIGHT 1\n";
    out << "VIEWPOINT 0 0 0 1 0 0 0\n";
    out << "POINTS " << points.size() << "\n";
    out << "DATA " << (binary_format ? "binary\n" : "ascii\n");

    if (binary_format) {
        #pragma pack(push, 1)
        struct PcdVertex {
            float x, y, z, intensity;
            uint32_t rgb;
        };
        #pragma pack(pop)
        for (const auto& pt : points) {
            uint32_t rgb_packed = (static_cast<uint32_t>(pt.r) << 16) |
                                  (static_cast<uint32_t>(pt.g) << 8) |
                                  static_cast<uint32_t>(pt.b);
            PcdVertex v{
                static_cast<float>(pt.x),
                static_cast<float>(pt.y),
                static_cast<float>(pt.z),
                pt.intensity,
                rgb_packed
            };
            out.write(reinterpret_cast<const char*>(&v), sizeof(PcdVertex));
        }
    } else {
        out << std::fixed << std::setprecision(5);
        for (const auto& pt : points) {
            uint32_t rgb_packed = (static_cast<uint32_t>(pt.r) << 16) |
                                  (static_cast<uint32_t>(pt.g) << 8) |
                                  static_cast<uint32_t>(pt.b);
            out << pt.x << " " << pt.y << " " << pt.z << " "
                << pt.intensity << " " << rgb_packed << "\n";
        }
    }
    return out.good();
}

bool PointCloudExporter::readFromPcd(const std::string& file_path,
                                     std::vector<core::LidarPointXYZIRT>& out_points) {
    out_points.clear();
    std::ifstream in(file_path, std::ios::binary);
    if (!in.is_open()) return false;

    std::string line;
    bool is_binary = false;
    size_t points_count = 0;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.rfind("POINTS ", 0) == 0) {
            points_count = std::stoull(line.substr(7));
        }
        if (line.rfind("DATA ", 0) == 0) {
            is_binary = (line.find("binary") != std::string::npos);
            break;
        }
    }

    out_points.reserve(points_count);
    if (is_binary) {
        #pragma pack(push, 1)
        struct PcdVertex {
            float x, y, z, intensity;
            uint32_t rgb;
        };
        #pragma pack(pop)
        for (size_t i = 0; i < points_count; ++i) {
            PcdVertex v{};
            in.read(reinterpret_cast<char*>(&v), sizeof(PcdVertex));
            if (!in.good()) return false;
            core::LidarPointXYZIRT pt;
            pt.x = v.x; pt.y = v.y; pt.z = v.z;
            pt.intensity = v.intensity;
            pt.r = static_cast<uint8_t>((v.rgb >> 16) & 0xFFu);
            pt.g = static_cast<uint8_t>((v.rgb >> 8) & 0xFFu);
            pt.b = static_cast<uint8_t>(v.rgb & 0xFFu);
            pt.colorized = true;
            out_points.push_back(pt);
        }
    } else {
        for (size_t i = 0; i < points_count; ++i) {
            core::LidarPointXYZIRT pt;
            uint32_t rgb_packed = 0;
            if (!(in >> pt.x >> pt.y >> pt.z >> pt.intensity >> rgb_packed)) return false;
            pt.r = static_cast<uint8_t>((rgb_packed >> 16) & 0xFFu);
            pt.g = static_cast<uint8_t>((rgb_packed >> 8) & 0xFFu);
            pt.b = static_cast<uint8_t>(rgb_packed & 0xFFu);
            pt.colorized = true;
            out_points.push_back(pt);
        }
    }
    return out_points.size() == points_count;
}

namespace {
// Helper to convert logical byte offset (excluding 4-byte CRC per 1020 logical bytes) to physical file offset
inline uint64_t logicalToPhysicalOffset(uint64_t logical_offset) {
    uint64_t page = logical_offset / 1020ULL;
    uint64_t rem = logical_offset % 1020ULL;
    return page * 1024ULL + rem;
}
}  // namespace

bool PointCloudExporter::exportToE57(const std::string& file_path,
                                     const std::vector<core::LidarPointXYZIRT>& points,
                                     const std::string& scan_guid,
                                     const std::string& scan_name) {
    // ASTM E2807-11 E57 file layout:
    // Logical stream is divided into 1020-byte chunks, each followed by a 4-byte big-endian CRC32C checksum (1024-byte physical page).
    // 1. E57FileHeader (48 bytes at logical offset 0)
    // 2. CompressedVectorSectionHeader (32 bytes at logical offset 48)
    // 3. Sequence of DataPackets (each <= 65536 bytes, aligned cleanly inside logical stream)
    // 4. XML section at end of compressed vector section, padded to full 1020-byte logical page boundary.

    #pragma pack(push, 1)
    struct E57FileHeader {
        char file_signature[8];      // "ASTM-E57"
        uint32_t major_version;      // 1
        uint32_t minor_version;      // 0
        uint64_t file_physical_len;
        uint64_t xml_physical_offset;
        uint64_t xml_logical_len;
        uint64_t page_size;          // 1024
    };

    struct CompressedVectorSectionHeader {
        uint8_t section_id;          // 1 = COMPRESSED_VECTOR_SECTION
        uint8_t reserved[7];         // must be zero
        uint64_t section_logical_len;
        uint64_t data_physical_offset;
        uint64_t index_physical_offset;
    };
    #pragma pack(pop)

    // We pack 7 bytestreams per point: cartesianX(double), cartesianY(double), cartesianZ(double),
    // intensity(double), colorRed(uint8), colorGreen(uint8), colorBlue(uint8)
    // Using 500 points per DataPacket so each packet fits well within 64 KB
    constexpr size_t kPointsPerPacket = 500;
    constexpr uint16_t kNumStreams = 7;

    std::vector<uint8_t> section_bytes;
    section_bytes.resize(sizeof(CompressedVectorSectionHeader), 0);

    size_t idx = 0;
    while (idx < points.size()) {
        size_t chunk_n = std::min(kPointsPerPacket, points.size() - idx);
        uint16_t len_x = static_cast<uint16_t>(chunk_n * sizeof(double));
        uint16_t len_y = static_cast<uint16_t>(chunk_n * sizeof(double));
        uint16_t len_z = static_cast<uint16_t>(chunk_n * sizeof(double));
        uint16_t len_i = static_cast<uint16_t>(chunk_n * sizeof(double));
        uint16_t len_r = static_cast<uint16_t>(chunk_n * sizeof(uint8_t));
        uint16_t len_g = static_cast<uint16_t>(chunk_n * sizeof(uint8_t));
        uint16_t len_b = static_cast<uint16_t>(chunk_n * sizeof(uint8_t));

        size_t payload_bytes = len_x + len_y + len_z + len_i + len_r + len_g + len_b;
        size_t header_bytes = 6 + kNumStreams * 2;  // 20 bytes
        size_t raw_pkt_len = header_bytes + payload_bytes;
        size_t padded_pkt_len = (raw_pkt_len + 3u) & ~size_t(3u);  // 4-byte multiple per ASTM E2807

        size_t pkt_start = section_bytes.size();
        section_bytes.resize(pkt_start + padded_pkt_len, 0);
        uint8_t* p = section_bytes.data() + pkt_start;

        p[0] = 1;  // DataPacket = 1
        p[1] = 0;  // flags = 0
        uint16_t len_minus_1 = static_cast<uint16_t>(padded_pkt_len - 1);
        std::memcpy(p + 2, &len_minus_1, 2);
        uint16_t stream_cnt = kNumStreams;
        std::memcpy(p + 4, &stream_cnt, 2);

        uint16_t stream_lens[kNumStreams] = {len_x, len_y, len_z, len_i, len_r, len_g, len_b};
        for (uint16_t s = 0; s < kNumStreams; ++s) {
            std::memcpy(p + 6 + s * 2, &stream_lens[s], 2);
        }

        uint8_t* cursor = p + header_bytes;
        for (size_t k = 0; k < chunk_n; ++k) {
            double v = points[idx + k].x;
            std::memcpy(cursor + k * sizeof(double), &v, sizeof(double));
        }
        cursor += len_x;
        for (size_t k = 0; k < chunk_n; ++k) {
            double v = points[idx + k].y;
            std::memcpy(cursor + k * sizeof(double), &v, sizeof(double));
        }
        cursor += len_y;
        for (size_t k = 0; k < chunk_n; ++k) {
            double v = points[idx + k].z;
            std::memcpy(cursor + k * sizeof(double), &v, sizeof(double));
        }
        cursor += len_z;
        for (size_t k = 0; k < chunk_n; ++k) {
            double v = static_cast<double>(points[idx + k].intensity);
            std::memcpy(cursor + k * sizeof(double), &v, sizeof(double));
        }
        cursor += len_i;
        for (size_t k = 0; k < chunk_n; ++k) cursor[k] = points[idx + k].r;
        cursor += len_r;
        for (size_t k = 0; k < chunk_n; ++k) cursor[k] = points[idx + k].g;
        cursor += len_g;
        for (size_t k = 0; k < chunk_n; ++k) cursor[k] = points[idx + k].b;

        idx += chunk_n;
    }

    uint64_t cv_logical_offset = sizeof(E57FileHeader);  // 48
    uint64_t data_logical_offset = cv_logical_offset + sizeof(CompressedVectorSectionHeader);  // 80
    uint64_t cv_section_logical_len = section_bytes.size();

    CompressedVectorSectionHeader cv_hdr{};
    cv_hdr.section_id = 1;
    cv_hdr.section_logical_len = cv_section_logical_len;
    cv_hdr.data_physical_offset = logicalToPhysicalOffset(data_logical_offset);
    cv_hdr.index_physical_offset = 0;
    std::memcpy(section_bytes.data(), &cv_hdr, sizeof(cv_hdr));

    uint64_t xml_logical_offset = cv_logical_offset + cv_section_logical_len;
    uint64_t xml_physical_offset = logicalToPhysicalOffset(xml_logical_offset);
    uint64_t cv_physical_offset = logicalToPhysicalOffset(cv_logical_offset);

    std::ostringstream xml_ss;
    xml_ss << "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
           << "<e57Root type=\"Structure\" xmlns=\"http://www.astm.org/COMMIT/E57/2010-e57-v1.0\">\n"
           << "  <formatName type=\"String\"><![CDATA[ASTM E57 3D Imaging Data File]]></formatName>\n"
           << "  <guid type=\"String\"><![CDATA[" << scan_guid << "]]></guid>\n"
           << "  <versionMajor type=\"Integer\">1</versionMajor>\n"
           << "  <versionMinor type=\"Integer\">0</versionMinor>\n"
           << "  <e57LibraryVersion type=\"String\"><![CDATA[AVScan-E57-1.0]]></e57LibraryVersion>\n"
           << "  <data3D type=\"Vector\" allowHeterogeneousChildren=\"1\">\n"
           << "    <vectorChild type=\"Structure\">\n"
           << "      <guid type=\"String\"><![CDATA[" << scan_guid << "-scan0]]></guid>\n"
           << "      <name type=\"String\"><![CDATA[" << scan_name << "]]></name>\n"
           << "      <points type=\"CompressedVector\" fileOffset=\"" << cv_physical_offset
           << "\" recordCount=\"" << points.size() << "\">\n"
           << "        <prototype type=\"Structure\">\n"
           << "          <cartesianX type=\"Float\" precision=\"double\"/>\n"
           << "          <cartesianY type=\"Float\" precision=\"double\"/>\n"
           << "          <cartesianZ type=\"Float\" precision=\"double\"/>\n"
           << "          <intensity type=\"Float\" precision=\"double\"/>\n"
           << "          <colorRed type=\"Integer\" minimum=\"0\" maximum=\"255\"/>\n"
           << "          <colorGreen type=\"Integer\" minimum=\"0\" maximum=\"255\"/>\n"
           << "          <colorBlue type=\"Integer\" minimum=\"0\" maximum=\"255\"/>\n"
           << "        </prototype>\n"
           << "        <codecs type=\"Vector\" allowHeterogeneousChildren=\"1\"/>\n"
           << "      </points>\n"
           << "    </vectorChild>\n"
           << "  </data3D>\n"
           << "</e57Root>\n";
    std::string xml_str = xml_ss.str();

    uint64_t total_unpadded_logical = xml_logical_offset + xml_str.size();
    uint64_t total_pages = (total_unpadded_logical + 1019ULL) / 1020ULL;
    uint64_t total_logical_padded = total_pages * 1020ULL;
    uint64_t file_physical_len = total_pages * 1024ULL;

    E57FileHeader file_hdr{};
    std::memcpy(file_hdr.file_signature, "ASTM-E57", 8);
    file_hdr.major_version = 1;
    file_hdr.minor_version = 0;
    file_hdr.file_physical_len = file_physical_len;
    file_hdr.xml_physical_offset = xml_physical_offset;
    file_hdr.xml_logical_len = xml_str.size();
    file_hdr.page_size = 1024;

    std::vector<uint8_t> logical_stream(total_logical_padded, 0);
    std::memcpy(logical_stream.data(), &file_hdr, sizeof(file_hdr));
    std::memcpy(logical_stream.data() + cv_logical_offset, section_bytes.data(), section_bytes.size());
    std::memcpy(logical_stream.data() + xml_logical_offset, xml_str.data(), xml_str.size());
    // Pad trailing space after XML with spaces/newlines so XML parsers see whitespace padding
    for (size_t i = xml_logical_offset + xml_str.size(); i < total_logical_padded; ++i) {
        logical_stream[i] = ' ';
    }

    std::ofstream out(file_path, std::ios::binary | std::ios::trunc);
    if (!out.is_open()) return false;

    for (uint64_t page = 0; page < total_pages; ++page) {
        const uint8_t* page_data = logical_stream.data() + page * 1020ULL;
        uint32_t crc = computeE57Crc32c(page_data, 1020);
        uint8_t crc_be[4] = {
            static_cast<uint8_t>((crc >> 24) & 0xFFu),
            static_cast<uint8_t>((crc >> 16) & 0xFFu),
            static_cast<uint8_t>((crc >> 8) & 0xFFu),
            static_cast<uint8_t>(crc & 0xFFu)
        };
        out.write(reinterpret_cast<const char*>(page_data), 1020);
        out.write(reinterpret_cast<const char*>(crc_be), 4);
    }
    return out.good();
}

bool PointCloudExporter::readFromE57(const std::string& file_path,
                                     std::vector<core::LidarPointXYZIRT>& out_points) {
    out_points.clear();
    std::ifstream in(file_path, std::ios::binary | std::ios::ate);
    if (!in.is_open()) return false;

    std::streamsize phys_len = in.tellg();
    if (phys_len <= 0 || (phys_len % 1024) != 0) return false;
    in.seekg(0, std::ios::beg);

    size_t num_pages = static_cast<size_t>(phys_len / 1024);
    std::vector<uint8_t> logical_stream(num_pages * 1020);

    for (size_t p = 0; p < num_pages; ++p) {
        uint8_t page_buf[1024]{};
        in.read(reinterpret_cast<char*>(page_buf), 1024);
        if (!in.good()) return false;
        uint32_t expected_crc = (static_cast<uint32_t>(page_buf[1020]) << 24) |
                                (static_cast<uint32_t>(page_buf[1021]) << 16) |
                                (static_cast<uint32_t>(page_buf[1022]) << 8) |
                                static_cast<uint32_t>(page_buf[1023]);
        uint32_t actual_crc = computeE57Crc32c(page_buf, 1020);
        if (actual_crc != expected_crc) return false;
        std::memcpy(logical_stream.data() + p * 1020, page_buf, 1020);
    }

    if ( std::memcmp(logical_stream.data(), "ASTM-E57", 8) != 0 ) return false;

    uint64_t xml_phys_off = 0, xml_log_len = 0;
    std::memcpy(&xml_phys_off, logical_stream.data() + 24, 8);
    std::memcpy(&xml_log_len, logical_stream.data() + 32, 8);

    uint64_t xml_log_off = (xml_phys_off / 1024ULL) * 1020ULL + (xml_phys_off % 1024ULL);
    if (xml_log_off + xml_log_len > logical_stream.size()) return false;

    std::string xml(reinterpret_cast<const char*>(logical_stream.data() + xml_log_off),
                    static_cast<size_t>(xml_log_len));
    if (xml.find("<e57Root") == std::string::npos || xml.find("<points") == std::string::npos) {
        return false;
    }

    size_t rec_pos = xml.find("recordCount=\"");
    if (rec_pos == std::string::npos) return false;
    rec_pos += 13;
    size_t rec_end = xml.find('"', rec_pos);
    size_t total_records = std::stoull(xml.substr(rec_pos, rec_end - rec_pos));

    // Parse CompressedVectorSection starting at logical offset 48
    size_t cursor = 48 + 32;  // Skip E57FileHeader (48) + CompressedVectorSectionHeader (32)
    out_points.reserve(total_records);

    while (out_points.size() < total_records && cursor + 20 <= xml_log_off) {
        const uint8_t* p = logical_stream.data() + cursor;
        if (p[0] != 1) break;  // DataPacket = 1
        uint16_t len_minus_1 = 0, stream_cnt = 0;
        std::memcpy(&len_minus_1, p + 2, 2);
        std::memcpy(&stream_cnt, p + 4, 2);
        if (stream_cnt != 7) return false;

        uint16_t lens[7]{};
        for (int s = 0; s < 7; ++s) {
            std::memcpy(&lens[s], p + 6 + s * 2, 2);
        }
        size_t chunk_n = lens[0] / sizeof(double);
        const uint8_t* d_ptr = p + 20;
        const double* xs = reinterpret_cast<const double*>(d_ptr); d_ptr += lens[0];
        const double* ys = reinterpret_cast<const double*>(d_ptr); d_ptr += lens[1];
        const double* zs = reinterpret_cast<const double*>(d_ptr); d_ptr += lens[2];
        const double* is = reinterpret_cast<const double*>(d_ptr); d_ptr += lens[3];
        const uint8_t* rs = d_ptr; d_ptr += lens[4];
        const uint8_t* gs = d_ptr; d_ptr += lens[5];
        const uint8_t* bs = d_ptr;

        for (size_t k = 0; k < chunk_n && out_points.size() < total_records; ++k) {
            core::LidarPointXYZIRT pt;
            pt.x = xs[k];
            pt.y = ys[k];
            pt.z = zs[k];
            pt.intensity = static_cast<float>(is[k]);
            pt.r = rs[k];
            pt.g = gs[k];
            pt.b = bs[k];
            pt.colorized = true;
            out_points.push_back(pt);
        }

        cursor += static_cast<size_t>(len_minus_1) + 1;
    }

    return out_points.size() == total_records;
}

